'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const view = fs.readFileSync(path.join(root,'inc/views/pages/crm-client.php'),'utf8');
const css = fs.readFileSync(path.join(root,'assets/frontend/crm.css'),'utf8');
const sprite = fs.readFileSync(path.join(root,'../../themes/hello-elementor-child/logos-icons/icons.svg'),'utf8');
const expected = {
  phone_call: 'icon-phone-call',
  email_sent: 'icon-envelope',
  wa_sent: 'icon-whatsapp',
  options_sent: 'icon-property',
  general: 'icon-notes'
};
for (const [type, icon] of Object.entries(expected)) {
  assert.match(view, new RegExp("'"+type+"'\\s*=>\\s*'"+icon+"'"), 'type maps to icon: '+type);
  assert.ok(sprite.includes('<symbol id="'+icon+'"'), 'sprite contains '+icon);
}
assert.match(view, /get_stylesheet_directory_uri\(\).*logos-icons\/icons\.svg#/, 'sprite URL generated by theme');
assert.match(view, /class="crm-note-activity-icon"[^>]*aria-hidden="true"[^>]*focusable="false"/, 'decorative icons hidden from accessibility API');
assert.match(view, /esc_html\(\s*\$note_type_labels\[\s*\$note_type\s*\]\s*\)/, 'accessible text label preserved');
assert.match(view, /isset\(\s*\$note_type_labels\[\s*\$note_type\s*\]\s*\)/, 'historical uncategorized notes remain unlabeled');
assert.match(css, /\.crm-note-activity-chip\s*\{[\s\S]*?display:\s*inline-flex;[\s\S]*?gap:\s*5px;/, 'pill is compact inline flex');
assert.match(css, /\.crm-note-activity-icon\s*\{[\s\S]*?width:\s*14px;[\s\S]*?height:\s*14px;/, 'icons are consistently sized');
console.log('PASS Advisor Notes icons: five types, sprite symbols, compact styling and accessible labels.');
