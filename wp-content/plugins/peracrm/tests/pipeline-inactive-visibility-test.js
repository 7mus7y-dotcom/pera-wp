'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = fs.readFileSync(path.join(root,'inc/frontend-data/crm-data.php'),'utf8');
const view = fs.readFileSync(path.join(root,'inc/views/pages/crm-pipeline.php'),'utf8');
const css = fs.readFileSync(path.join(root,'assets/frontend/crm.css'),'utf8');
const start = data.indexOf('function pera_crm_get_pipeline_view_data(): array {');
const end = data.indexOf("if ( ! function_exists( 'pera_crm_get_performance_range_options' ) )",start);
assert.ok(start >= 0 && end > start, 'pipeline loader located');
const pipeline = data.slice(start,end);
assert.match(pipeline, /isset\(\s*\$_GET\['include_inactive'\]\s*\)\s*&&\s*'1' === \(string\) wp_unslash\(\s*\$_GET\['include_inactive'\]\s*\)/, 'explicit opt-in required');
assert.match(pipeline, /!\s*\$include_inactive\s*&&\s*in_array\(\s*\$engagement,\s*array\(\s*'closed',\s*'dormant'\s*\),\s*true\s*\)/, 'closed and dormant omitted by default');
const filter = pipeline.indexOf("if ( ! $include_inactive && in_array(");
const add = pipeline.indexOf("$board[ $stage_key ]['items'][]");
assert.ok(filter > 0 && add > filter, 'exclusion before row inserted');
const counts = pipeline.indexOf("$board[ $stage_key ]['count'] = count(");
assert.ok(counts > add, 'counts reflect filtered rows');
assert.match(pipeline, /'include_inactive'\s*=>\s*\$include_inactive/, 'visibility state passed to view');
assert.match(pipeline, /'engagement_state'\s*=>\s*\$engagement/, 'engagement kept in item data');
assert.match(pipeline, /'post__in'\s*\]/, 'existing permission scope retained');
assert.match(view, /name="include_inactive"\s+value="1"/, 'toggle uses GET');
assert.match(view, /checked\(\s*\$include_inactive\s*\)/, 'toggle retains state');
assert.match(view, /array\(\s*'q',\s*'stage',\s*'advisor'\s*\)/, 'other filters preserved');
assert.match(view, /onchange="this\.form\.submit\(\)"/, 'toggle applies without JS assets');
assert.match(css, /\.crm-page--pipeline \.crm-pipeline-visibility-filter/, 'scoped styling');
console.log('PASS Pipeline excludes closed/dormant by default, includes on opt-in, preserves existing filters and counts.');
